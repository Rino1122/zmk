void zmk_ptp_protocol_init(struct zmk_ptp_protocol *s) {
    *s = (struct zmk_ptp_protocol){.selective = 3};
}
int zmk_ptp_feature_pad(uint8_t id) {
    unsigned pad = (id >> 4) - 1;
    return pad < ZMK_PTP_PAD_COUNT && (id & 15) >= 1 && (id & 15) <= 5 ? (int)pad : -1;
}
int zmk_ptp_feature_get(const struct zmk_ptp_protocol *s, uint8_t id, uint8_t *data,
                        size_t capacity) {
    if (!s || !data || zmk_ptp_feature_pad(id) < 0)
        return -ENOTSUP;
    size_t size = (id & 15) == 2 ? 256 : (id & 15) == 1 ? 2 : 1;
    if (capacity < size)
        return -EMSGSIZE;
    switch (id & 15) {
    case 1:
        data[0] = ZMK_PTP_CONTACTS;
        data[1] = 2;
        break; /* Non-clickable */
    case 2:
        memcpy(data, certification, size);
        break;
    case 3:
        data[0] = s->mode;
        break;
    case 4:
        data[0] = s->selective;
        break;
    case 5:
        data[0] = s->latency;
        break;
    }
    return (int)size;
}
int zmk_ptp_feature_set(struct zmk_ptp_protocol *s, uint8_t id, const uint8_t *data,
                        size_t length) {
    if (!s || !data || zmk_ptp_feature_pad(id) < 0)
        return -ENOTSUP;
    if ((id & 15) <= 2)
        return -ENOTSUP;
    if (length != 1)
        return -EINVAL;
    switch (id & 15) {
    case 3:
        s->mode = data[0] == 3 ? 3 : 0;
        break;
    case 4:
        if (data[0] > 3)
            return -EINVAL;
        s->selective = data[0];
        break;
    case 5:
        if (data[0] > 1)
            return -EINVAL;
        s->latency = data[0];
        break;
    }
    return 0;
}
int zmk_ptp_encode(const struct zmk_ptp_frame *frame, uint8_t body[ZMK_PTP_BODY_SIZE]) {
    if (!frame || !body || frame->count > ZMK_PTP_CONTACTS)
        return -EINVAL;
    for (unsigned i = 0; i < frame->count; i++) {
        const struct zmk_ptp_contact *c = &frame->contacts[i];
        if (c->x > ZMK_PTP_COORD_MAX || c->y > ZMK_PTP_COORD_MAX)
            return -ERANGE;
        for (unsigned j = 0; j < i; j++)
            if (c->id == frame->contacts[j].id)
                return -EINVAL;
    }
    memset(body, 0, ZMK_PTP_BODY_SIZE);
    for (unsigned i = 0; i < frame->count; i++) {
        const struct zmk_ptp_contact *c = &frame->contacts[i];
        uint8_t *p = body + i * 6;
        p[0] = (c->confidence ? ZMK_PTP_CONFIDENCE : 0) | (c->tip ? ZMK_PTP_TIP : 0);
        p[1] = c->id;
        p[2] = c->x;
        p[3] = c->x >> 8;
        p[4] = c->y;
        p[5] = c->y >> 8;
    }
    body[24] = frame->scan_time;
    body[25] = frame->scan_time >> 8;
    body[26] = frame->count;
    return 0;
}
void zmk_ptp_encode_up(uint8_t body[ZMK_PTP_BODY_SIZE]) {
    for (unsigned i = 0; i < ZMK_PTP_CONTACTS; i++)
        body[i * 6] &= ~ZMK_PTP_TIP;
}
